let _city = null;

export function getCityFromHostname() {
  if (typeof window === "undefined") return null;
  const host = window.location.hostname;
  const match = host.match(/^([a-z0-9_-]+)\.openai2000\.cn$/i);
  if (!match) return null;
  const sub = match[1].toLowerCase();
  const name = CITY_MAP[sub];
  if (!name) return null;
  _city = { subdomain: sub, name };
  return _city;
}

export function getCity() {
  if (_city) return _city;
  return getCityFromHostname();
}

export function t(text) {
  const c = getCity();
  if (!c || !text) return text;
  return text.replace(/青岛/g, c.name);
}

export default { getCityFromHostname, getCity, t };